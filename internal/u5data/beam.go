const (
	// BeamSectorCount 是扇區數(= 一圈幾幀)。
	BeamSectorCount = 16
	// BeamWidth 是光束同時亮幾個扇區(`sub_2E944` 開頭點 0/1/2 三個)。
	BeamWidth = 3
	// BeamOffDaylight 是「亮到這個程度就不畫光束了」(`cmp byte_3E0B5, 32h`)。
	BeamOffDaylight = 0x32
)

// BeamCells 是第 n 個扇區實際涵蓋的格子(已經去掉填充)。
func BeamCells(sector int) [][2]int {
	s := ((sector % BeamSectorCount) + BeamSectorCount) % BeamSectorCount
	var out [][2]int
	for _, p := range BeamSectors[s] {
		if p[0] == 0 && p[1] == 0 {
			continue
		}
		out = append(out, [2]int{int(p[0]), int(p[1])})
	}
	return out
}

// 明文訊息的譯文覆蓋層
//
// `STORY.DAT` / `QUESTION.DAT` / `KARMA.DAT` / `MISCMSG.DAT` / `ENDMSG.DAT`
// 這五個檔是 NUL 分隔的純 ASCII,共 114 筆,**沒有詞典 token**
// (`SHOPPE.DAT` 有,所以不在這裡)。
//
// key 是 `檔名#序號`。序號就是 `u5data.TextRecord.Index` ——
// 也就是原版靠 NUL 數出來的第幾筆。
//
// # 譯法
//
// 對白與敘述用**中世紀羊皮紙腔**(汝 / 卿 / 吾),對齊《軟體世界》手冊的語氣;
// 系統提示用平白的現代中文,因為那是介面不是劇情。
//
// # 原文裡要留意的三件事
//
//  1. **`_` 是英文的斷字提示**(`be_gin`、`mys_te_ri_ous`),解碼時已經去掉了。
//     中文不斷字,所以譯文裡不會有。
//  2. **有些記錄是句子的前半**,後面由程式接上變數。例如
//     `MISCMSG#0` 結尾是「…the Mystic Shrine of 」後面接美德名。
//     這種**譯文結尾也要留成可接的形狀**,不要自己補句號。
//  3. **`MISCMSG#41..44` 是符文字母**(`[`=TH、`^`=EA、`]`=NG、`_`=ST、
//     `@`=空白、`o`=句號),原版用 `RUNES.CH` 畫成符文。這裡照語意翻成中文,
//     連句號一起還原成「。」—— 留著 `o` 在中文裡只會被當成錯字。
//     符文字型那條路還沒做,做了之後這幾筆要重新決定
//     (見 `docs/localization-notes.md`)。
var texts = map[string]string{}

// TextKey 組出譯文表的 key。
func TextKey(file string, index int) string { return fmt.Sprintf("%s#%d", file, index) }

// Text 查一筆明文訊息的譯文。查不到就回原文。
func Text(file string, index int, en string) string {
	if zh, ok := texts[TextKey(file, index)]; ok {
		return zh
	}
	return en
}

// TextTranslated 回報這一筆翻過了沒。用來統計覆蓋率。
func TextTranslated(file string, index int) bool {
	_, ok := texts[TextKey(file, index)]
	return ok
}

// TextCount 是已翻的筆數。
func TextCount() int { return len(texts) }

func init() {
	addText(introText)
	addText(karmaText)
	addText(endText)
	addText(miscText)
	addText(storyText)
	addText(questionText)
}

func addText(m map[string]string) {
	for k, v := range m {
		texts[k] = v
	}
}

